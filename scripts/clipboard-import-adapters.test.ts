import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import test from "node:test";
import ts from "typescript";

import { maskCodeRegions } from "../packages/markdown/src/core";
import { clipboardMarkdownTitle, prepareClipboardMarkdownFile } from "../packages/platform/src/imports/clipboard-client";

const root = path.resolve(import.meta.dirname, "..");

test("David clipboard files open unsaved drafts through every registered notebook and the scaffold", async () => {
  const registry = JSON.parse(await readFile(path.join(root, "babel.apps.json"), "utf8")) as {
    apps: { id: string; workspace: string }[];
  };
  // Synthetic output generated by David's real Chromium conversation fixture.
  const markdown = await readFile(path.join(root, "packages/markdown/tests/fixtures/david-conversation.md"), "utf8");
  const file = prepareClipboardMarkdownFile(markdown, clipboardMarkdownTitle(markdown));

  for (const target of [...registry.apps, { id: "template", workspace: "templates/mirror-app" }]) {
    const archive = target.id === "retex" || target.id === "matter";
    const neum = target.id === "neum";
    const listName = archive ? "item-list" : neum ? "entry-list" : "note-list";
    const workspaceName = archive ? "archive-workspace" : neum ? "entries-workspace" : "notes-workspace";
    const directory = path.join(root, target.workspace);
    const [list, workspace, parserSource, limits] = await Promise.all([
      readFile(path.join(directory, "src/components", `${listName}.tsx`), "utf8"),
      readFile(path.join(directory, "src/components", `${workspaceName}.tsx`), "utf8"),
      readFile(path.join(directory, "src/lib/markdown-import.ts"), "utf8"),
      import(pathToFileURL(path.join(directory, "src/lib", neum ? "entry-limits.ts" : "note-limits.ts")).href),
    ]);
    assert.match(list, /<ClipboardMarkdownImportAction\s+onImport=\{onImport\}/u, `${target.id}: keep the existing import adapter`);
    assert.match(list, /id: "(?:note|item|entry)\.importClipboard"/u, `${target.id}: command palette entry`);
    assert.match(list, /run: \(\) => clipboardImportOpenRef\.current\?\.\(\)/u);
    assert.match(list, /registerOpen=\{\(open\) => \{ clipboardImportOpenRef\.current = open; \}\}/u);
    assert.match(list, /<ClipboardMarkdownImportAction\s+onImport=\{onImport\}\s+disabled=\{selectedFolderId === null \|\| referencePanelOpen\}/u);

    const actionSource = /\{\s+id: "(?:note|item|entry)\.importClipboard",[\s\S]*?\n    \}/u.exec(list)?.[0];
    assert.ok(actionSource);
    const actionFor = (folder: number | null, reference: boolean, mode = "knowledge") => new Function(
      "selectedFolderId", "referencePanelOpen", "type", "kind", "onImport", "clipboardImportOpenRef",
      `return (${actionSource});`,
    )(folder, reference, mode, mode, () => undefined, { current: null }) as { available: boolean };
    assert.equal(actionFor(7, false).available, true, target.id);
    assert.equal(actionFor(null, false).available, false, target.id);
    assert.equal(actionFor(7, true).available, false, `${target.id}: reference panels block palette imports`);
    if (archive || neum) assert.equal(actionFor(7, false, "snippet").available, false, target.id);

    const parserExports = {} as { parseMarkdownImport: (name: string, bytes: Uint8Array) => unknown };
    new Function("require", "exports", ts.transpileModule(parserSource, {
      compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
    }).outputText)((id: string) => {
      if (id.endsWith("note-limits") || id.endsWith("entry-limits")) return limits;
      if (id === "@babel-apps/markdown/core") return { maskCodeRegions };
      throw new Error(`Unexpected import dependency: ${id}`);
    }, parserExports);

    const source = ts.createSourceFile("workspace.tsx", workspace, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
    let handler: ts.FunctionDeclaration | undefined;
    function visit(node: ts.Node) {
      if (ts.isFunctionDeclaration(node) && node.name?.text === "handleImportMarkdown") handler = node;
      else ts.forEachChild(node, visit);
    }
    visit(source);
    assert.ok(handler, `${target.id}: actual workspace import handler`);
    const drafts: Record<string, unknown>[] = [];
    const errors: string[] = [];
    const variables = {
      selectedFolderId: 7, type: "knowledge", kind: "knowledge",
      NOTE_CONTENT_MAX_BYTES: 10 * 1024 * 1024, ENTRY_NOTES_MAX_BYTES: 10 * 1024 * 1024,
      parseMarkdownImport: parserExports.parseMarkdownImport,
      openDraft: (draft: Record<string, unknown>) => drafts.push(draft),
      setError: (error: string) => errors.push(error),
      setNavigationError: (error: string) => errors.push(error),
      getErrorMessage: (error: Error) => error.message,
    };
    const code = ts.transpileModule(handler.getText(source), {
      compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.None },
    }).outputText;
    const run = new Function(...Object.keys(variables), `${code}\nreturn handleImportMarkdown;`)(...Object.values(variables)) as (file: File) => Promise<void>;
    await run(file);
    assert.deepEqual(errors, [], target.id);
    assert.equal(drafts.length, 1, target.id);
    assert.equal(drafts[0].folderId, 7, target.id);
    assert.deepEqual(drafts[0].importDraft, {
      title: clipboardMarkdownTitle(markdown), contentMd: markdown, imageReferences: [], originalDocument: undefined,
    }, target.id);
  }
});
